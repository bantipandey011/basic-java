package Basic;

public class arithmaticOperationOnInt {
    public static void main(String[] args) {
        int x =29, y=3;
        System.out.println(x+y);
        System.out.println(x-y);
        System.out.println(x/y);
        double a=39;
        double b=4;
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a/b);
    }
    
}
