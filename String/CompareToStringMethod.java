package String;

public class CompareToStringMethod {
    public static void main(String[] args) {
        String a="raghav";
        String b="ram";
        System.out.println(a.compareTo(b));
        System.out.println(b.compareTo(a));
        String c="ramnivas";
        String d="ramni";
        System.out.println(c.compareTo(d));
        System.out.println(d.compareTo(c));
    }
    
}
