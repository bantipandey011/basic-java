package String;

public class PlusString3 {
    public static void main(String[] args) {
        String s="ram";
        s+=" hi sakti hai";
        System.out.println(s);
        s+=10;
        System.out.println(s);
        s+='a';
        System.out.println(s);
        s+="\n";
        System.out.println(s);
        s+="n";
        System.out.println(s);
    }
    
}
