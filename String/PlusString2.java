package String;

public class PlusString2 {
    public static void main(String[] args) {
        String a="gitanjali";
        String b="priyal";
        a=a+b;
        System.out.println(a);
        a+=b;
        System.out.println(a);
        a+=10;
        System.out.println(a);
        a+='a';
        System.out.println(a);
        
    }
    
}
